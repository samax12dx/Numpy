#عمليات حسابية
import numpy as np
a=np.array([2,3,4])
b=np.array([5,6,7])
#جمع مصفوفتين
print(a+b)
print("\n")
#ضرب مصفوفتين
print(a*b)
#الاس
print(a**2)
#المتوسط الحسابي 
arr=np.array([10,20,30,40])
print(np.mean(arr))
#المجموع الكلي 
print(np.sum(arr))
#القيمة الصغرى 
print(np.min(arr))
#القيمة الكبرى 
print(np.max(arr))
#الانحراف المعياري 
print(np.std(arr))
